-- 1. Campos de presentacion para cada prenda del catalogo
ALTER TABLE inventario ADD COLUMN IF NOT EXISTS imagen_url  TEXT DEFAULT '';
ALTER TABLE inventario ADD COLUMN IF NOT EXISTS descripcion TEXT DEFAULT '';
ALTER TABLE inventario ADD COLUMN IF NOT EXISTS tallas      TEXT DEFAULT 'S, M, L';
ALTER TABLE inventario ADD COLUMN IF NOT EXISTS visible     BOOLEAN DEFAULT true;
ALTER TABLE inventario ADD COLUMN IF NOT EXISTS destacado   BOOLEAN DEFAULT false;
-- Genero de la prenda: 'Mujer', 'Hombre' o 'Unisex' (la tienda lo usa como filtro)
ALTER TABLE inventario ADD COLUMN IF NOT EXISTS genero      TEXT DEFAULT 'Unisex';

-- 2. Vista publica: SOLO datos seguros (sin costo, sin margen, sin proveedor)
CREATE OR REPLACE VIEW catalogo_publico AS
SELECT id, nombre, categoria, pvp, stock, imagen_url, descripcion, tallas, destacado, genero
FROM inventario
WHERE COALESCE(visible, true) = true;

GRANT SELECT ON catalogo_publico TO anon;

-- 3. Validar un codigo de embajadora SIN exponer la tabla de embajadoras
CREATE OR REPLACE FUNCTION validar_codigo(p_codigo TEXT)
RETURNS JSON
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    (SELECT json_build_object(
              'valido', true,
              'embajadora', split_part(nombre, ' ', 1),
              'beneficio', descuento_amigo)
       FROM embajadores
      WHERE upper(codigo) = upper(trim(p_codigo))
      LIMIT 1),
    json_build_object('valido', false)
  );
$$;

GRANT EXECUTE ON FUNCTION validar_codigo(TEXT) TO anon;

-- 4. Solicitudes de la bolsa (lo que piden los clientes desde la tienda)
CREATE TABLE IF NOT EXISTS solicitudes (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    cliente TEXT DEFAULT '',
    telefono TEXT DEFAULT '',
    codigo TEXT DEFAULT '',
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    total NUMERIC(10,2) NOT NULL DEFAULT 0,
    atendida BOOLEAN DEFAULT false,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE solicitudes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "tienda inserta solicitudes" ON solicitudes;
CREATE POLICY "tienda inserta solicitudes" ON solicitudes
  FOR INSERT WITH CHECK (true);

-- La suite interna (misma llave) necesita leerlas y marcarlas como atendidas
DROP POLICY IF EXISTS "suite lee solicitudes" ON solicitudes;
CREATE POLICY "suite lee solicitudes" ON solicitudes FOR SELECT USING (true);
DROP POLICY IF EXISTS "suite actualiza solicitudes" ON solicitudes;
CREATE POLICY "suite actualiza solicitudes" ON solicitudes FOR UPDATE USING (true);
