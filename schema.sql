CREATE POLICY "Permitir actualizacion publica embajadores" ON embajadores FOR UPDATE USING (true);
CREATE POLICY "Permitir eliminacion publica embajadores" ON embajadores FOR DELETE USING (true);

CREATE POLICY "Permitir lectura publica inventario" ON inventario FOR SELECT USING (true);
CREATE POLICY "Permitir insercion publica inventario" ON inventario FOR INSERT WITH CHECK (true);
CREATE POLICY "Permitir actualizacion publica inventario" ON inventario FOR UPDATE USING (true);
CREATE POLICY "Permitir eliminacion publica inventario" ON inventario FOR DELETE USING (true);

CREATE POLICY "Permitir lectura publica pedidos" ON pedidos FOR SELECT USING (true);
CREATE POLICY "Permitir insercion publica pedidos" ON pedidos FOR INSERT WITH CHECK (true);
CREATE POLICY "Permitir actualizacion publica pedidos" ON pedidos FOR UPDATE USING (true);
