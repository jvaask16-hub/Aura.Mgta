-- 1. TABLA: embajadores (Afiliados y Embajadores)
CREATE TABLE IF NOT EXISTS embajadores (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre TEXT NOT NULL,
    telefono TEXT DEFAULT '',
    instagram TEXT DEFAULT '',
    codigo TEXT UNIQUE NOT NULL,
    invitado_por_codigo TEXT DEFAULT '',
    meta INT DEFAULT 5,
    premio TEXT DEFAULT '$10.00 OFF en su compra',
    descuento_amigo TEXT DEFAULT '10% OFF en su primera compra',
    elegibilidad TEXT DEFAULT 'solo_nuevos',
    monto_minimo_compra NUMERIC(10,2) DEFAULT 30.00,
    usos INT DEFAULT 0,
    reclamado BOOLEAN DEFAULT false,
    historial JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABLA: inventario (Catálogo de prendas)
CREATE TABLE IF NOT EXISTS inventario (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre TEXT NOT NULL,
    categoria TEXT DEFAULT 'General',
    costo NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    pvp NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    stock INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA: pedidos (Planillas y Órdenes Históricas)
CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    numero_planilla TEXT UNIQUE NOT NULL,
    cliente TEXT NOT NULL,
    telefono TEXT DEFAULT '',
    tipo_cliente TEXT DEFAULT 'Cliente Nuevo',
    codigo_embajador TEXT DEFAULT '',
    embajador_nombre TEXT,
    embajador_id BIGINT REFERENCES embajadores(id) ON DELETE SET NULL,
    fecha TEXT NOT NULL,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    subtotal_pvp_regular NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    total_descuentos_prendas NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    subtotal_tras_descuento_prendas NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    total_descuento_global NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    costo_envio_cliente NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    tipo_envio TEXT DEFAULT 'gratis',
    total_a_pagar_cliente NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    gasto_total_tienda NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    ganancia_neta_cuenta NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    margen_porcentaje_cuenta NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    ticket_texto TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. HABILITAR ROW LEVEL SECURITY (RLS) & POLÍTICAS PÚBLICAS PARA CLIENTE ANÓNIMO (Anon Key)
ALTER TABLE embajadores ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventario ENABLE ROW LEVEL SECURITY;
ALTER TABLE pedidos ENABLE ROW LEVEL SECURITY;

